"""
Utility functions for logging, exception handling, data fetching, and feature engineering.
"""

import logging
import yfinance as yf
import pandas as pd
import ta
import os

# --- Exceptions ---
class DataFetchError(Exception):
    """Raised when there is an error fetching data from yfinance."""
    pass

class InvalidTickerError(Exception):
    """Raised when the provided ticker is invalid or returns no data."""
    pass

class ModelLoadError(Exception):
    """Raised when the model or scaler fails to load."""
    pass


# --- Logging Setup ---
def setup_logger(name: str) -> logging.Logger:
    """
    Sets up a configured logger.
    """
    logger = logging.getLogger(name)
    if not logger.handlers:
        logger.setLevel(logging.INFO)
        formatter = logging.Formatter('%(asctime)s - %(name)s - %(levelname)s - %(message)s')
        
        # Console Handler
        ch = logging.StreamHandler()
        ch.setFormatter(formatter)
        logger.addHandler(ch)
        
    return logger

logger = setup_logger(__name__)

# --- Data Fetching ---
def fetch_stock_data(ticker: str, start_date: str, end_date: str = None) -> pd.DataFrame:
    """
    Fetches historical stock data using yfinance.
    
    Args:
        ticker (str): Stock ticker symbol.
        start_date (str): Start date in YYYY-MM-DD format.
        end_date (str, optional): End date in YYYY-MM-DD format. Defaults to None (today).
        
    Returns:
        pd.DataFrame: DataFrame containing historical data.
    """
    try:
        logger.info(f"Fetching data for {ticker} from {start_date} to {end_date or 'today'}")
        df = yf.download(ticker, start=start_date, end=end_date, progress=False)
        
        if df.empty:
            raise InvalidTickerError(f"No data found for ticker {ticker}. It may be delisted or invalid.")
        
        # Flatten MultiIndex columns if they exist (yfinance sometimes returns multi-index)
        if isinstance(df.columns, pd.MultiIndex):
            df.columns = df.columns.get_level_values(0)
            
        return df
    except Exception as e:
        logger.error(f"Error fetching data for {ticker}: {str(e)}")
        raise DataFetchError(f"Failed to fetch data for {ticker}. Check internet connection or ticker validity.") from e


# --- Technical Indicators ---
def add_technical_indicators(df: pd.DataFrame) -> pd.DataFrame:
    """
    Computes and adds advanced technical indicators to the DataFrame using the `ta` library.
    
    Args:
        df (pd.DataFrame): Raw historical data with Open, High, Low, Close, Volume.
        
    Returns:
        pd.DataFrame: DataFrame with added technical indicators.
    """
    logger.info("Calculating technical indicators...")
    df_ta = df.copy()
    
    # RSI
    df_ta['RSI'] = ta.momentum.RSIIndicator(close=df_ta['Close'], window=14).rsi()
    
    # MACD
    macd = ta.trend.MACD(close=df_ta['Close'])
    df_ta['MACD'] = macd.macd()
    
    # EMA & SMA
    df_ta['EMA_20'] = ta.trend.EMAIndicator(close=df_ta['Close'], window=20).ema_indicator()
    df_ta['SMA_50'] = ta.trend.SMAIndicator(close=df_ta['Close'], window=50).sma_indicator()
    
    # Bollinger Bands
    bollinger = ta.volatility.BollingerBands(close=df_ta['Close'], window=20, window_dev=2)
    df_ta['BB_High'] = bollinger.bollinger_hband()
    df_ta['BB_Low'] = bollinger.bollinger_lband()
    
    # ATR (Average True Range)
    atr = ta.volatility.AverageTrueRange(high=df_ta['High'], low=df_ta['Low'], close=df_ta['Close'], window=14)
    df_ta['ATR'] = atr.average_true_range()
    
    # Drop rows with NaN values generated by indicator windows
    df_ta.dropna(inplace=True)
    
    logger.info(f"Technical indicators added. Data shape: {df_ta.shape}")
    return df_ta
